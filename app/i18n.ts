function translatePattern(text: string): string {
  const exact = SPANISH_TRANSLATIONS[text];
  if (exact) return exact;

  const eachTeamCompact = text.match(/^Each Team ([0-9]+)\+ (.+)$/);
  if (eachTeamCompact) {
    return `Cada equipo ${eachTeamCompact[1]}+ ${translateUiText('es', eachTeamCompact[2])}`;
  }

  const eachTeamOver = text.match(/^Each Team Over ([0-9.]+) (.+)$/);
  if (eachTeamOver) {
    return `Cada equipo más de ${eachTeamOver[1]} ${translateUiText('es', eachTeamOver[2])}`;
  }

  const over = text.match(/^Over ([0-9.]+) (.+)$/);
  if (over) {
    return `Más de ${over[1]} ${translateUiText('es', over[2])}`;
  }

  const under = text.match(/^Under ([0-9.]+) (.+)$/);
  if (under) {
    return `Menos de ${under[1]} ${translateUiText('es', under[2])}`;
  }

  const leagueOnly = text.match(/^(.*) \*league only$/);
  if (leagueOnly) {
    return `${translateUiText('es', leagueOnly[1])} *solo liga`;
  }

  return text;
}

export function isAppLanguage(value: string | null | undefined): value is AppLanguage {
  return value === 'en' || value === 'es';
}

export function getLanguageLocale(language: AppLanguage) {
  return language === 'es' ? 'es-ES' : 'en-GB';
}

export function translateUiText(language: AppLanguage, text: string) {
  if (language === 'en') return text;
  return translatePattern(text);
}
